def main() -> int:
    raw_url = os.getenv("DATABASE_URL", "")
    if not raw_url:
        print("DATABASE_URL is required", file=sys.stderr)
        return 2

    dsn = raw_url.replace("postgresql+asyncpg://", "postgresql://", 1)
    conn = psycopg2.connect(dsn)
    conn.autocommit = False

    try:
        with conn.cursor() as cur:
            # 1. Update course title + backfill description if empty
            cur.execute(
                "UPDATE courses SET title = %s WHERE id = %s AND title IS DISTINCT FROM %s",
                (NEW_COURSE_TITLE, COURSE_ID, NEW_COURSE_TITLE),
            )
            print(f"course title updated: {cur.rowcount}")

            cur.execute(
                """
                UPDATE courses SET description = %s
                WHERE id = %s
                  AND (description IS NULL OR description = '' OR description LIKE '%%???%%')
                """,
                (NEW_COURSE_DESCRIPTION, COURSE_ID),
            )
            print(f"course description backfilled: {cur.rowcount}")

            # 2. Rename mismatched module titles
            for old, new in MODULE_TITLE_RENAMES.items():
                cur.execute(
                    "UPDATE modules SET title = %s WHERE course_id = %s AND title = %s",
                    (new, COURSE_ID, old),
                )
                print(f"module rename {old!r} -> {new!r}: {cur.rowcount}")

            # 3. Per-lesson update
            for module_title, data in LESSONS.items():
                cur.execute(
                    """
                    SELECT m.id, l.id, l.content, l.promo_description, l.promo_highlights
                    FROM modules m
                    JOIN lessons l ON l.module_id = m.id
                    WHERE m.course_id = %s AND m.title = %s
                    ORDER BY l.order_index
                    LIMIT 1
                    """,
                    (COURSE_ID, module_title),
                )
                row = cur.fetchone()
                if row is None:
                    print(f"!! module not found: {module_title}", file=sys.stderr)
                    continue
                _module_id, lesson_id, cur_content, cur_desc, cur_high = row

                desired_high = {"bullets": data["promo_bullets"]}
                if (
                    cur_content == data["content"]
                    and cur_desc == data["promo_description"]
                    and cur_high == desired_high
                ):
                    print(f"  {module_title:30s}  no change")
                    continue

                cur.execute(
                    """
                    UPDATE lessons
                    SET content = %s,
                        promo_description = %s,
                        promo_highlights = %s::jsonb
                    WHERE id = %s
                    """,
                    (
                        data["content"],
                        data["promo_description"],
                        json.dumps(desired_high, ensure_ascii=False),
                        str(lesson_id),
                    ),
                )
                print(f"  {module_title:30s}  updated (rows={cur.rowcount})")

            # 4. Mojibake cleanup: legacy '???' chars from a bad import.
            cur.execute(
                """
                UPDATE lessons l
                SET description = l.promo_description
                FROM modules m
                WHERE l.module_id = m.id
                  AND m.course_id = %s
                  AND (l.description LIKE %s OR l.description IS NULL OR l.description = '')
                  AND l.promo_description IS NOT NULL AND l.promo_description != ''
                """,
                (COURSE_ID, '%???%'),
            )
            print(f"lesson.description mojibake cleanup: {cur.rowcount}")

            cur.execute(
                """
                UPDATE modules SET description = NULL
                WHERE course_id = %s AND description LIKE %s
                """,
                (COURSE_ID, '%???%'),
            )
            print(f"module.description mojibake cleared: {cur.rowcount}")

            # 5. Verification
            cur.execute(
                "SELECT title FROM courses WHERE id = %s", (COURSE_ID,)
            )
            (course_title,) = cur.fetchone()
            cur.execute(
                """
                SELECT m.title, l.content IS NOT NULL AND length(l.content) > 0,
                       l.promo_description IS NOT NULL AND length(l.promo_description) > 0,
                       l.promo_highlights IS NOT NULL
                FROM modules m
                JOIN lessons l ON l.module_id = m.id
                WHERE m.course_id = %s
                ORDER BY m.order_index
                """,
                (COURSE_ID,),
            )
            rows = cur.fetchall()
            print()
            print(f"Course: {course_title}")
            print(f"Lessons populated:")
            for title, has_c, has_d, has_h in rows:
                marks = ("C" if has_c else "-") + ("D" if has_d else "-") + ("H" if has_h else "-")
                print(f"  [{marks}]  {title}")

            missing = [r for r in rows if not (r[1] and r[2] and r[3])]
            if missing:
                raise RuntimeError(f"{len(missing)} lessons still incomplete; rolling back")

        conn.commit()
        print()
        print("OK: committed")
        return 0
    except Exception as e:
        conn.rollback()
        print(f"FAILED: {e}; rolled back", file=sys.stderr)
        return 1
    finally:
        conn.close()


if __name__ == "__main__":
    raise SystemExit(main())
