"""
Сопоставление файлов из video-lessons/ с темами программы и порядком модулей.
"""

from __future__ import annotations

import unicodedata
from dataclasses import dataclass


@dataclass(frozen=True)
class VideoCatalogEntry:
    """Один источник правды для имени файла и заголовка урока на лендинге."""

    filename_pattern: str  # подстрока для glob / match (латиница или кириллица как в репо)
    slug: str
    title: str  # как в разделе «Программа курса»
    order: int


# Порядок как в frontend/src/app/page.tsx (COURSE_DATA.modules)
VIDEO_CATALOG: list[VideoCatalogEntry] = [
    VideoCatalogEntry("фольга", "folga", "Фольга", 1),
    VideoCatalogEntry("аквариум", "akvarium", "Аквариум", 2),
    VideoCatalogEntry("втирка", "vtirka", "Втирка", 3),
    VideoCatalogEntry("слайдер", "slaidery", "Слайдеры и наклейки", 4),
    VideoCatalogEntry("френч", "french", "Френч", 5),
    VideoCatalogEntry("пигмент", "pigmenty", "Пигменты", 6),
    VideoCatalogEntry("стемпинг", "stemping", "Стемпинг", 7),
    VideoCatalogEntry("страз", "strazy", "Стразы/объемные украшения", 8),
    VideoCatalogEntry("текстур", "tekstury", "Текстуры", 9),
    VideoCatalogEntry("градиент", "gradient", "Градиент", 10),
    VideoCatalogEntry("аэрограф", "aerografiya", "Аэрография", 11),
]


def find_catalog_entry(filename: str) -> VideoCatalogEntry | None:
    """Подобрать запись каталога по имени файла (без учёта регистра)."""
    # Windows/репо: «й» в имени файла иногда NFD (и + combining), ломая `in` с шаблоном.
    lower = unicodedata.normalize("NFC", filename.lower())
    for entry in VIDEO_CATALOG:
        pat = unicodedata.normalize("NFC", entry.filename_pattern.lower())
        if pat in lower:
            return entry
    return None


